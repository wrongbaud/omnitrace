// The sample the reference streams were made from: an LCG picks words, with
// occasional random bytes, and a 300-byte copy 4400 bytes back when the
// sample is long enough (a match distance above 0xd00).
Bytes reference_sample(std::size_t n) {
    static const char* words[] = {"alpha ", "bravo ",   "charlie ", "delta ",
                                  "echo ",  "foxtrot ", "golf ",    "hotel "};
    Bytes b(n);
    std::uint32_t x = 12345;
    std::size_t p = 0;
    while (p < n) {
        x = x * 1103515245u + 12345u;
        const char* w = words[(x >> 16) & 7];
        std::size_t l = std::strlen(w);
        if (p + l > n) l = n - p;
        std::memcpy(b.data() + p, w, l);
        p += l;
        if (((x >> 8) & 15) == 0) {
            for (unsigned k = 0; k < 6 && p < n; ++k) {
                x = x * 1103515245u + 12345u;
                b[p++] = static_cast<std::uint8_t>(x >> 24);
            }
        }
    }
    if (n > 5000) std::memcpy(b.data() + 4500, b.data() + 100, 300);
    return b;
}

