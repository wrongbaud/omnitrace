// The NRV2B bit stream, writer side. Bits fill a byte reserved in the stream
// when the first of its eight bits is written; stored bytes that follow land
// after it, which is where the decoder reloads its bit buffer.
struct BitStream {
    Bytes out;
    std::size_t bit_pos = 0;
    unsigned bits_left = 0;

    void put_bit(std::uint64_t b) {
        if (bits_left == 0) {
            bit_pos = out.size();
            out.push_back(0);
            bits_left = 8;
        }
        --bits_left;
        if (b != 0) out[bit_pos] |= static_cast<std::uint8_t>(1u << bits_left);
    }
    void put_byte(std::uint8_t b) { out.push_back(b); }
    // Prefix code for v >= 2: the bits below the leading one, most
    // significant first, each followed by a stop bit (1 after the last).
    void put_prefix(std::uint64_t v) {
        int top = 63;
        while (top > 0 && ((v >> top) & 1) == 0) --top;
        for (int k = top - 1; k >= 0; --k) {
            put_bit((v >> k) & 1);
            put_bit(k == 0 ? 1 : 0);
        }
    }
    void put_end() {
        put_bit(0);
        put_prefix(0x1000002);
        put_byte(0xff);
    }
};

// A greedy NRV2B encoder: enough of the bit stream to feed the decoder every
// construct it knows. Not tuned for ratio; the reference vectors above cover
// what a real encoder emits.
class Nrv2bEncoder {
   public:
    // `window` bounds the match search; `use_repeat` emits the "same offset
    // as before" code when it applies.
    explicit Nrv2bEncoder(std::size_t window = 1u << 16, bool use_repeat = true)
        : window_(window), use_repeat_(use_repeat) {}

    Bytes encode(const Bytes& in) {
        BitStream s;
        std::uint64_t last_off = 1;
        std::size_t i = 0;
        while (i < in.size()) {
            std::size_t best_len = 0, best_off = 0;
            find_match(in, i, best_len, best_off);
            const std::uint64_t extra = best_off > 0xd00 ? 1 : 0;
            if (best_len < 2 + extra) {
                s.put_bit(1);
                s.put_byte(in[i]);
                ++i;
                continue;
            }
            s.put_bit(0);
            if (use_repeat_ && best_off == last_off) {
                s.put_prefix(2);
            } else {
                s.put_prefix(((best_off - 1) >> 8) + 3);
                s.put_byte(static_cast<std::uint8_t>((best_off - 1) & 0xff));
                last_off = best_off;
            }
            const std::uint64_t t = best_len - 1 - extra;  // >= 1
            if (t <= 3) {
                s.put_bit((t >> 1) & 1);
                s.put_bit(t & 1);
            } else {
                s.put_bit(0);
                s.put_bit(0);
                s.put_prefix(t - 2);  // >= 2
            }
            i += best_len;
        }
        s.put_end();
        return s.out;
    }

   private:
    void find_match(const Bytes& in, std::size_t i, std::size_t& len, std::size_t& off) const {
        len = 0;
        off = 0;
        const std::size_t start = i > window_ ? i - window_ : 0;
        for (std::size_t j = start; j < i; ++j) {
            std::size_t l = 0;
            while (i + l < in.size() && in[j + l] == in[i + l] && l < 4000) ++l;
            if (l > len) {
                len = l;
                off = i - j;
            }
        }
    }

    std::size_t window_;
    bool use_repeat_;
};

Bytes text_sample() {
    std::string s;
    for (int i = 0; i < 40; ++i)
        s += "line " + std::to_string(i) + ": the quick brown fox jumps over the lazy dog\n";
    return Bytes(s.begin(), s.end());
}

Bytes pseudo_random(std::size_t n, std::uint64_t seed) {
    Bytes v(n);
    std::uint64_t x = seed | 1;
    for (std::size_t i = 0; i < n; ++i) {
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        v[i] = static_cast<std::uint8_t>((x * 0x2545F4914F6CDD1Dull) >> 56);
    }
    return v;
}

