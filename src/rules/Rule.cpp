const char* kind_name(Kind k) {
    switch (k) {
        case Kind::Regex:
            return "regex";
        case Kind::Literal:
            return "literal";
        case Kind::Hex:
            return "hex";
        case Kind::GlobPath:
            return "glob-path";
    }
    return "regex";
}

const char* severity_name(Severity s) {
    switch (s) {
        case Severity::Info:
            return "info";
        case Severity::Low:
            return "low";
        case Severity::Medium:
            return "medium";
        case Severity::High:
            return "high";
        case Severity::Critical:
            return "critical";
    }
    return "medium";
}

bool parse_kind(std::string_view s, Kind& out) {
    if (s == "regex") return out = Kind::Regex, true;
    if (s == "literal") return out = Kind::Literal, true;
    if (s == "hex") return out = Kind::Hex, true;
    if (s == "glob-path") return out = Kind::GlobPath, true;
    return false;
}

bool parse_severity(std::string_view s, Severity& out) {
    if (s == "info") return out = Severity::Info, true;
    if (s == "low") return out = Severity::Low, true;
    if (s == "medium") return out = Severity::Medium, true;
    if (s == "high") return out = Severity::High, true;
    if (s == "critical") return out = Severity::Critical, true;
    return false;
}

Status RulePack::parse(std::string_view yaml, std::string_view origin, RulePack& out) {
    out = RulePack{};
    out.origin = std::string(origin);
    YAML::Node doc;
    try {
        doc = YAML::Load(std::string(yaml));
    } catch (const std::exception& e) {
        return Status::fail("rules-bad-yaml: " + std::string(origin) + ": " + e.what());
    }
    if (!doc.IsMap()) return Status::fail("rules-bad-yaml: " + std::string(origin) + ": not a map");

    out.name = node_str(doc, "pack");
    if (out.name.empty())
        return Status::fail("rules-no-name: " + std::string(origin) + ": 'pack' is required");
    if (const YAML::Node v = doc["version"]; v && v.IsScalar()) {
        try {
            out.version = v.as<std::uint32_t>();
        } catch (const std::exception&) {
            return Status::fail("rules-bad-version: " + out.name + ": 'version' is not a number");
        }
    }
    const YAML::Node list = doc["rules"];
    if (!list || !list.IsSequence())
        return Status::fail("rules-no-rules: " + out.name + ": 'rules' must be a sequence");

    std::map<std::string, std::size_t> seen;
    for (std::size_t i = 0; i < list.size(); ++i) {
        const YAML::Node n = list[i];
        const std::string where = out.name + ": rule[" + std::to_string(i) + "]";
        if (!n.IsMap()) return Status::fail("rules-bad-rule: " + where + " is not a map");

        Rule r;
        r.pack = out.name;
        r.id = node_str(n, "id");
        if (r.id.empty()) return Status::fail("rules-no-id: " + where + ": 'id' is required");
        if (!seen.emplace(r.id, i).second)
            return Status::fail("rules-duplicate-id: " + out.name + ": '" + r.id +
                                "' is defined twice");
        r.category = node_str(n, "category", "other");
        r.description = node_str(n, "description");
        r.pattern = node_str(n, "pattern");
        if (r.pattern.empty())
            return Status::fail("rules-no-pattern: " + out.name + ": '" + r.id +
                                "': 'pattern' is required");
        const std::string kind = node_str(n, "kind", "regex");
        if (!parse_kind(kind, r.kind))
            return Status::fail("rules-bad-kind: " + out.name + ": '" + r.id + "': '" + kind +
                                "' is not regex, literal, hex or glob-path");
        const std::string sev = node_str(n, "severity", "medium");
        if (!parse_severity(sev, r.severity))
            return Status::fail("rules-bad-severity: " + out.name + ": '" + r.id + "': '" + sev +
                                "' is not info, low, medium, high or critical");
        r.validate = node_str(n, "validate");
        if (!known_filter(r.validate))
            return Status::fail("rules-bad-validate: " + out.name + ": '" + r.id + "': '" +
                                r.validate +
                                "' is not a built-in filter (vin-checksum, luhn, "
                                "mac-not-broadcast)");
        if (const YAML::Node sc = n["scope"]; sc && sc.IsSequence()) {
            r.in_files = r.in_regions = false;
            for (const YAML::Node& s : sc) {
                const std::string v = s.as<std::string>();
                if (v == "files")
                    r.in_files = true;
                else if (v == "regions")
                    r.in_regions = true;
                else
                    return Status::fail("rules-bad-scope: " + out.name + ": '" + r.id + "': '" + v +
                                        "' is not files or regions");
            }
            if (!r.in_files && !r.in_regions)
                return Status::fail("rules-empty-scope: " + out.name + ": '" + r.id +
                                    "': 'scope' lists nothing");
        }
        out.rules.push_back(std::move(r));
    }
    if (out.rules.empty())
        return Status::fail("rules-no-rules: " + out.name + ": the pack defines no rules");
    return Status::success();
}

Status RulePack::load_file(const std::string& path, RulePack& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return Status::fail("rules-unreadable: cannot open '" + path + "'");
    std::ostringstream ss;
    ss << f.rdbuf();
    return parse(ss.str(), path, out);
}

const std::vector<RulePack>& RulePack::builtin() {
    static const std::vector<RulePack> packs = [] {
        std::vector<RulePack> v;
        for (std::size_t i = 0; i < detail::kEmbeddedRulesCount; ++i) {
            const auto& e = detail::kEmbeddedRules[i];
            RulePack p;
            const std::string_view text(reinterpret_cast<const char*>(e.data), e.size);
            if (RulePack::parse(text, e.name, p)) v.push_back(std::move(p));
        }
        return v;
    }();
    return packs;
}

// ------------------------------------------------------------------- Engine

struct Engine::Impl {
    struct Compiled {
        Rule rule;
        std::unique_ptr<RE2> re;  // for locating, once the set says it matched
    };
    std::vector<Compiled> content;
    std::vector<Rule> paths;
    std::unique_ptr<RE2::Set> set;
};

Engine::Engine() : impl_(std::make_unique<Impl>()) {}
Engine::~Engine() = default;
Engine::Engine(Engine&&) noexcept = default;
Engine& Engine::operator=(Engine&&) noexcept = default;

Status Engine::build(const std::vector<RulePack>& packs, Engine& out) {
    out.impl_ = std::make_unique<Impl>();
    Impl& d = *out.impl_;

    RE2::Options opts;
    opts.set_encoding(RE2::Options::EncodingLatin1);  // a byte is a byte
    opts.set_log_errors(false);
    opts.set_max_mem(64 << 20);
    opts.set_never_capture(true);

    d.set = std::make_unique<RE2::Set>(opts, RE2::UNANCHORED);
    for (const RulePack& p : packs) {
        for (const Rule& r : p.rules) {
            if (r.kind == Kind::GlobPath) {
                d.paths.push_back(r);
                continue;
            }
            bool ok = true;
            const std::string pattern = to_regex(r, ok);
            if (!ok)
                return Status::fail("rules-bad-pattern: " + p.name + ": '" + r.id +
                                    "': not a valid " + kind_name(r.kind) + " pattern");
            std::string err;
            if (d.set->Add(pattern, &err) < 0)
                return Status::fail("rules-bad-pattern: " + p.name + ": '" + r.id + "': " + err);
            auto re = std::make_unique<RE2>(pattern, opts);
            if (!re->ok())
                return Status::fail("rules-bad-pattern: " + p.name + ": '" + r.id +
                                    "': " + re->error());
            d.content.push_back(Impl::Compiled{r, std::move(re)});
        }
    }
    if (!d.set->Compile())
        return Status::fail("rules-set-too-large: the combined patterns exceed RE2's memory bound");
    return Status::success();
}

std::size_t Engine::content_rules() const {
    return impl_ ? impl_->content.size() : 0;
}

std::size_t Engine::path_rules() const {
    return impl_ ? impl_->paths.size() : 0;
}

void Engine::scan_bytes(std::span<const std::uint8_t> data, bool in_files, const ScanLimits& lim,
                        std::vector<Hit>& out) const {
    if (!impl_ || impl_->content.empty() || data.empty()) return;
    const Impl& d = *impl_;
    const std::size_t n =
        static_cast<std::size_t>(std::min<std::uint64_t>(data.size(), lim.max_bytes_per_item));
    const re2::StringPiece subject(reinterpret_cast<const char*>(data.data()), n);

    // Phase one: which rules match anywhere at all. Usually none, and that is
    // one pass over the buffer rather than one pass per rule.
    std::vector<int> matched;
    if (!d.set->Match(subject, &matched)) return;

    const std::size_t before = out.size();
    for (const int idx : matched) {
        if (idx < 0 || static_cast<std::size_t>(idx) >= d.content.size()) continue;
        const Impl::Compiled& c = d.content[static_cast<std::size_t>(idx)];
        if (in_files ? !c.rule.in_files : !c.rule.in_regions) continue;

        // Phase two: locate this rule's matches.
        std::uint64_t kept = 0;
        re2::StringPiece rest = subject;
        while (kept < lim.max_hits_per_rule_per_item && !rest.empty()) {
            re2::StringPiece m;
            if (!c.re->Match(subject, static_cast<std::size_t>(rest.data() - subject.data()),
                             subject.size(), RE2::UNANCHORED, &m, 1))
                break;
            const std::size_t at = static_cast<std::size_t>(m.data() - subject.data());
            const std::string_view text(m.data(), m.size());
            if (passes(c.rule.validate, text)) {
                Hit h;
                h.rule = c.rule.id;
                h.pack = c.rule.pack;
                h.category = c.rule.category;
                h.severity = c.rule.severity;
                h.offset = at;
                h.match =
                    quote_bytes(std::span<const std::uint8_t>(data.data() + at, m.size()), 160);
                const std::size_t ctx_from = at > lim.context_bytes ? at - lim.context_bytes : 0;
                const std::size_t ctx_to = std::min(n, at + m.size() + lim.context_bytes);
                h.context = quote_bytes(
                    std::span<const std::uint8_t>(data.data() + ctx_from, ctx_to - ctx_from), 400);
                out.push_back(std::move(h));
                ++kept;
            }
            // Always move on by at least one byte: an empty match would spin.
            const std::size_t next = at + std::max<std::size_t>(m.size(), 1);
            if (next >= n) break;
            rest = re2::StringPiece(subject.data() + next, n - next);
        }
    }
    // Deterministic order, so a manifest is byte-identical run to run.
    std::sort(out.begin() + static_cast<std::ptrdiff_t>(before), out.end(),
              [](const Hit& a, const Hit& b) {
                  if (a.offset != b.offset) return a.offset < b.offset;
                  if (a.pack != b.pack) return a.pack < b.pack;
                  return a.rule < b.rule;
              });
}

void Engine::scan_path(const std::string& path, std::vector<Hit>& out) const {
    if (!impl_) return;
    for (const Rule& r : impl_->paths) {
        if (!glob_match(r.pattern, path)) continue;
        Hit h;
        h.rule = r.id;
        h.pack = r.pack;
        h.category = r.category;
        h.severity = r.severity;
        h.offset = 0;
        h.match = sanitize_utf8(path);
        out.push_back(std::move(h));
    }
    std::sort(out.begin(), out.end(), [](const Hit& a, const Hit& b) {
        if (a.pack != b.pack) return a.pack < b.pack;
        return a.rule < b.rule;
    });
}

