std::string hex_to_regex(std::string_view pattern, bool& ok) {
    std::string out;
    std::string digits;
    for (const char c : pattern) {
        if (std::isspace(static_cast<unsigned char>(c)) != 0) continue;
        digits.push_back(c);
    }
    ok = digits.size() % 2 == 0 && !digits.empty();
    if (!ok) return {};
    for (std::size_t i = 0; i + 1 < digits.size(); i += 2) {
        const std::string byte = digits.substr(i, 2);
        if (byte == "??" || byte == "**") {
            out += "(?s).";  // any byte, newline included
            continue;
        }
        const bool hex = std::isxdigit(static_cast<unsigned char>(byte[0])) != 0 &&
                         std::isxdigit(static_cast<unsigned char>(byte[1])) != 0;
        if (!hex) {
            ok = false;
            return {};
        }
        out += "\\x{" + byte + "}";
    }
    return out;
}

// A rule's pattern as RE2 sees it. Literal and hex are lowered to regex so one
// set covers every kind and a scan stays a single pass.
std::string to_regex(const Rule& r, bool& ok) {
    ok = true;
    switch (r.kind) {
        case Kind::Regex:
            return r.pattern;
        case Kind::Literal:
            return RE2::QuoteMeta(r.pattern);
        case Kind::Hex:
            return hex_to_regex(r.pattern, ok);
        case Kind::GlobPath:
            break;
    }
    ok = false;
    return {};
}

// Shell-style glob over a path, matched a path segment at a time. Splitting
// on '/' first is what makes this both correct and cheap: inside a segment
// there is no separator, so '*' and '?' are the classic two-pointer glob with
// no backtracking subtleties, and only '**' has to try several segment counts
// -- and a path is a handful of segments deep.
//
// Matching the whole string at once with one backtrack point, which is the
// usual shortcut, is wrong here: a '*' that stops at '/' can fail after a
// later '*' has already committed, and recovering needs to back up past it.
std::vector<std::string_view> split_path(std::string_view s) {
    std::vector<std::string_view> out;
    std::size_t start = 0;
    for (std::size_t i = 0; i <= s.size(); ++i) {
        if (i == s.size() || s[i] == '/') {
            out.push_back(s.substr(start, i - start));
            start = i + 1;
        }
    }
    return out;
}

// One segment: '*' matches any run of characters, '?' exactly one.
bool segment_match(std::string_view pat, std::string_view s) {
    std::size_t p = 0, t = 0, star = std::string_view::npos, star_t = 0;
    while (t < s.size()) {
        if (p < pat.size() && (pat[p] == '?' || pat[p] == s[t])) {
            ++p;
            ++t;
        } else if (p < pat.size() && pat[p] == '*') {
            star = p++;
            star_t = t;
        } else if (star != std::string_view::npos) {
            p = star + 1;
            t = ++star_t;
        } else {
            return false;
        }
    }
    while (p < pat.size() && pat[p] == '*') ++p;
    return p == pat.size();
}

bool glob_match(std::string_view pattern, std::string_view path) {
    const std::vector<std::string_view> pat = split_path(pattern);
    const std::vector<std::string_view> seg = split_path(path);
    // match[i][j]: pat[i..] matches seg[j..]. Bounded by the segment counts,
    // so a hostile pattern costs a table, not an exponential search.
    const std::size_t np = pat.size(), ns = seg.size();
    std::vector<std::uint8_t> table((np + 1) * (ns + 1), 0);
    const auto at = [&](std::size_t i, std::size_t j) -> std::uint8_t& {
        return table[i * (ns + 1) + j];
    };
    at(np, ns) = 1;
    for (std::size_t i = np; i-- > 0;) {
        for (std::size_t j = ns + 1; j-- > 0;) {
            if (pat[i] == "**") {
                // Zero segments, or one more and try again.
                at(i, j) = at(i + 1, j) != 0 || (j < ns && at(i, j + 1) != 0) ? 1 : 0;
            } else if (j < ns && segment_match(pat[i], seg[j])) {
                at(i, j) = at(i + 1, j + 1);
            }
        }
    }
    return at(0, 0) != 0;
}

