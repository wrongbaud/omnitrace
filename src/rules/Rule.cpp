// Rule.cpp — pack parsing, rule compilation and matching.
//
// Every content rule, whatever its kind, becomes one RE2 pattern and they all
// go into a single RE2::Set. A scan is then two phases: ask the set which
// rules match anywhere in the buffer (one pass, no offsets), and only for
// those run the individual pattern to locate each hit. The common case in a
// forensic image is "none of them", and that costs exactly one pass.
//
// RE2 runs in Latin-1 so a byte is a byte: evidence is not text, and a UTF-8
// mode would refuse to look at most of a flash dump.
#include "omnitrace/rules/Rule.h"

